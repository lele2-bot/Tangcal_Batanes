  /// Fills the form with this user's saved details so saving doesn't wipe
  /// fields they didn't retype. Reads only the signed-in user's documents.
  Future<void> _prefillFromProfile() async {
    final userRef = currentUserReference;
    if (userRef == null) {
      return;
    }
    void setIfEmpty(TextEditingController? c, String value) {
      if (c != null && c.text.isEmpty && value.isNotEmpty) {
        c.text = value;
      }
    }

    try {
      final user = await UsersRecord.getDocumentOnce(userRef);
      if (!mounted) return;
      setIfEmpty(_model.phoneNumberTextController, user.phoneNumber);
      final nameParts = user.displayName.trim().split(RegExp(r'\s+'));
      if (nameParts.first.isNotEmpty) {
        setIfEmpty(_model.firstNameTextController, nameParts.first);
        setIfEmpty(_model.lastNameTextController, nameParts.skip(1).join(' '));
      }

      switch (user.role) {
        case 'Customer':
          final c = await queryCustomersRecordOnce(
              queryBuilder: (q) => q.where('customer_id', isEqualTo: userRef),
              limit: 1);
          if (c.isNotEmpty && mounted) {
            setIfEmpty(_model.firstNameTextController, c.first.firstName);
            setIfEmpty(_model.lastNameTextController, c.first.lastName);
            setIfEmpty(_model.addressTextController, c.first.deliveryAddress);
          }
          break;
        case 'Business Owner':
          final r = await queryRestaurantsRecordOnce(
              queryBuilder: (q) => q.where('owner_id', isEqualTo: userRef),
              limit: 1);
          if (r.isNotEmpty && mounted) {
            final resto = r.first;
            setIfEmpty(_model.restaurantNameTextController, resto.restaurantName);
            setIfEmpty(_model.businessPermitTextController, resto.businessPermit);
            setIfEmpty(_model.addressTextController, resto.address);
            setIfEmpty(_model.shortdescTextController, resto.shortDescription);
          }
          break;
        case 'Delivery Rider':
          final r = await queryRiderRecordOnce(
              queryBuilder: (q) => q.where('rider_id', isEqualTo: userRef),
              limit: 1);
          if (r.isNotEmpty && mounted) {
            final rider = r.first;
            setIfEmpty(_model.firstNameTextController, rider.firstName);
            setIfEmpty(_model.lastNameTextController, rider.lastName);
            setIfEmpty(_model.vehicleModelTextController, rider.vehicleModel);
            setIfEmpty(_model.vehicleBrandTextController, rider.vehicleBrand);
            setIfEmpty(_model.vehicleColorTextController, rider.vehicleColor);
            if (rider.vehicleType.isNotEmpty) {
              _model.vehicleTypeValue = rider.vehicleType;
              _model.vehicleTypeValueController?.value = rider.vehicleType;
            }
          }
          break;
      }
      if (mounted) {
        safeSetState(() {});
      }
    } catch (_) {
      // Prefill is a convenience; the form still works empty.
    }
  }

